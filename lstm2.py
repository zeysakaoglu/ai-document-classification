def extract_text_from_pdf(pdf_path):                       # bu fonksiyon ile pdf icindeki metni texte cevirir.

    try:
        doc = fitz.open(pdf_path)                          # pdf dosyasini acip icindeki sayfalara erisebilmek icin
        full_text = []                                     # pdften okudugu metini bu listeye ekleyecek

        for page in doc:                                   # pdfteki tum sayfalari okuyabilmesi icin dongu
            text = page.get_text()                         # Sayfadan metni cekiyor
            full_text.append(text)                         # metni olusturdugumuz listeye ekler

        doc.close()                                        # pdf dosyasini kapatiyoruz

        return "\n".join(full_text).strip()                # okunan tum sayfalari birlestirir ve bastaki ve sondaki bosluklari siler.

    except Exception as e:                                 # hata blogu. pdf okunamazsa program cokmesin diye,
        print(f"PDF okunamadı: {pdf_path} → Hata: {e}")
        return ""

