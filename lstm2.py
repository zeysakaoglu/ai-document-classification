def predict_pdf_department_proba_lstm(model, tokenizer, label_encoder, pdf_path, max_seq_len):



    text = extract_text_from_pdf(pdf_path)  #pdften metni okur

    if not text.strip():
        print(f"Uyarı: PDF'ten metin okunamadı -> {pdf_path}")
        return None

    #  Metni temizle (küçük harf, noktalama sadeleştirme vs.)
    text_clean = clean_text(text)

    if not text_clean.strip():
        print(f"Uyarı: Temizleme sonrası metin boş -> {pdf_path}")
        return None

    #  Tokenizer + padding
    seq = tokenizer.texts_to_sequences([text_clean])
    padded = pad_sequences(seq, maxlen=max_seq_len, padding="post", truncating="post")

    #  Modelden olasılıkları al
    proba = model.predict(padded)[0]   # shape: (sınıf_sayısı,)

    #  Sınıf isimlerini al (LabelEncoder üzerinden)
    class_indices = np.arange(len(proba))
    class_names = label_encoder.inverse_transform(class_indices)  # örn: ['ar_ge', 'finans', ...]

    #  Sınıf-olasılık sözlüğü
    prob_dict = {cls: float(p) for cls, p in zip(class_names, proba)}

    # Büyükten küçüğe sırala
    prob_dict_sorted = dict(sorted(prob_dict.items(), key=lambda x: x[1], reverse=True))

    return prob_dict_sorted

